# STEP 3 — Dataset Coverage Score
# ═══════════════════════════════════════════════════════════════════════════════

def step3_dcs(df: pd.DataFrame) -> pd.DataFrame:
    log.info("=" * 60)
    log.info("STEP 3 — Computing Dataset Coverage Score (DCS)")
    log.info("=" * 60)

    norm_cols = [f"norm_{m}" for m in DCS_METRICS]
    n_metrics = len(norm_cols)

    # Equal-weight mean of normalized metrics
    df["Dataset_Coverage_Score"] = df[norm_cols].mean(axis=1).round(4)
    df["DCS_percent"]            = (df["Dataset_Coverage_Score"] * 100).round(2)

    log.info(f"  DCS formula: mean of {n_metrics} equally-weighted normalized metrics")
    log.info(f"  Metrics: {', '.join(DCS_METRICS)}")
    log.info(f"  DCS range: {df['Dataset_Coverage_Score'].min():.4f} – {df['Dataset_Coverage_Score'].max():.4f}")
    log.info(f"  DCS mean : {df['Dataset_Coverage_Score'].mean():.4f}")
    log.info(f"  DCS median: {df['Dataset_Coverage_Score'].median():.4f}")
    return df


