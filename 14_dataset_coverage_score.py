def step4_classify(df: pd.DataFrame) -> pd.DataFrame:
    log.info("=" * 60)
    log.info("STEP 4 — Classifying targets by DCS quintile")
    log.info("=" * 60)

    q80 = df["Dataset_Coverage_Score"].quantile(0.80)
    q60 = df["Dataset_Coverage_Score"].quantile(0.60)
    q40 = df["Dataset_Coverage_Score"].quantile(0.40)
    q20 = df["Dataset_Coverage_Score"].quantile(0.20)

    log.info(f"  Q20={q20:.4f}  Q40={q40:.4f}  Q60={q60:.4f}  Q80={q80:.4f}")

    conditions = [
        df["Dataset_Coverage_Score"] >= q80,
        (df["Dataset_Coverage_Score"] >= q60) & (df["Dataset_Coverage_Score"] < q80),
        (df["Dataset_Coverage_Score"] >= q40) & (df["Dataset_Coverage_Score"] < q60),
        (df["Dataset_Coverage_Score"] >= q20) & (df["Dataset_Coverage_Score"] < q40),
    ]
    choices = [
        "Excellent Coverage",
        "Good Coverage",
        "Moderate Coverage",
        "Limited Coverage",
    ]
    df["Coverage_Class"] = np.select(conditions, choices, default="Sparse Coverage")

    # Store thresholds for report
    df.attrs["q20"] = q20
    df.attrs["q40"] = q40
    df.attrs["q60"] = q60
    df.attrs["q80"] = q80

    for cls, cnt in df["Coverage_Class"].value_counts().items():
        log.info(f"    {cls:<25s}: {cnt:>5,}")

    return df


