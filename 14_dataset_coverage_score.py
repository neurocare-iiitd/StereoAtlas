# STEP 1 — Per-target statistics
# ═══════════════════════════════════════════════════════════════════════════════

def step1_target_statistics(pairs: pd.DataFrame,
                             minmax: pd.DataFrame,
                             lit: pd.DataFrame) -> pd.DataFrame:
    log.info("=" * 60)
    log.info("STEP 1 — Computing per-target statistics")
    log.info("=" * 60)

    # ── From TRUE_ISOMER_PAIRS ────────────────────────────────────────────────
    grp = pairs.groupby(["target_chembl_id", "target_name"])

    # 1. Unique compounds
    n_compounds = grp["compound_chembl_id"].nunique().rename("unique_compounds")

    # 2. Stereochemical families
    n_families = grp["stereochemical_family_id"].nunique().rename("stereochemical_families")

    # 3. True stereoisomer pairs = sum of C(n,2) per family per target
    fam_sizes = (
        pairs.groupby(["target_chembl_id", "stereochemical_family_id"])["compound_chembl_id"]
        .count()
        .reset_index(name="n_members")
    )
    fam_sizes["n_pairs"] = fam_sizes["n_members"].apply(lambda n: max(0, n * (n - 1) // 2))
    n_pairs = (
        fam_sizes.groupby("target_chembl_id")["n_pairs"]
        .sum()
        .rename("true_isomer_pairs")
    )

    # 4. Activity types
    n_actypes = grp["activity_type"].nunique().rename("activity_types")

    # 5. Organisms
    n_organisms = grp["organism"].nunique().rename("organisms")

    # 6. Total measurements (proxy for assay density)
    n_assays = grp["n_measurements"].sum().rename("total_measurements")

    # Assemble primary frame
    df = (
        n_compounds
        .to_frame()
        .join(n_families)
        .join(n_actypes)
        .join(n_organisms)
        .join(n_assays)
        .reset_index()
    )
    df = df.merge(n_pairs.reset_index(), on="target_chembl_id", how="left")

    # ── From FAMILY_MINMAX_FOLD ───────────────────────────────────────────────
    minmax["fold_difference"] = pd.to_numeric(minmax["fold_difference"], errors="coerce")
    finite_fold = minmax[np.isfinite(minmax["fold_difference"]) & (minmax["fold_difference"] > 0)]

    fold_stats = (
        finite_fold.groupby("target_chembl_id")["fold_difference"]
        .agg(
            median_fold_difference="median",
            maximum_fold_difference="max",
            mean_fold_difference="mean",
        )
        .reset_index()
    )

    # Strong / Extreme class counts
    strong_ct = (
        minmax[minmax["classification"] == "Strong"]
        .groupby("target_chembl_id").size()
        .reset_index(name="n_strong_families")
    )
    extreme_ct = (
        minmax[minmax["classification"] == "Extreme"]
        .groupby("target_chembl_id").size()
        .reset_index(name="n_extreme_families")
    )

    df = df.merge(fold_stats,  on="target_chembl_id", how="left")
    df = df.merge(strong_ct,   on="target_chembl_id", how="left")
    df = df.merge(extreme_ct,  on="target_chembl_id", how="left")
    df["n_strong_families"]  = df["n_strong_families"].fillna(0).astype(int)
    df["n_extreme_families"] = df["n_extreme_families"].fillna(0).astype(int)

    # ── From TRUE_ISOMER_LITERATURE_CLEAN ─────────────────────────────────────
    lit["publication_count"] = pd.to_numeric(lit["publication_count"], errors="coerce").fillna(0)

    # 6. Literature references = sum of publication_count per compound per target
    #    (unique at compound-family level to avoid double-counting)
    lit_unique = lit.drop_duplicates(
        subset=["target_chembl_id", "compound_chembl_id", "stereochemical_family_id"]
    )
    lit_refs = (
        lit_unique.groupby("target_chembl_id")["publication_count"]
        .sum()
        .rename("literature_references")
        .reset_index()
    )

    # 7. Unique PubMed IDs per target
    # pubmed_ids are single values (confirmed — not pipe-separated)
    lit_pmids = lit_unique[lit_unique["pubmed_ids"].notna() & (lit_unique["pubmed_ids"] != "nan")]
    pmid_ct = (
        lit_pmids.groupby("target_chembl_id")["pubmed_ids"]
        .nunique()
        .rename("unique_pubmed_ids")
        .reset_index()
    )

    df = df.merge(lit_refs, on="target_chembl_id", how="left")
    df = df.merge(pmid_ct,  on="target_chembl_id", how="left")
    df["literature_references"] = df["literature_references"].fillna(0)
    df["unique_pubmed_ids"]     = df["unique_pubmed_ids"].fillna(0).astype(int)

    # Fill fold stats NA (targets with no fold data) with 0 for normalization
    df["median_fold_difference"] = df["median_fold_difference"].fillna(0)
    df["maximum_fold_difference"] = df["maximum_fold_difference"].fillna(0)
    df["mean_fold_difference"]    = df["mean_fold_difference"].fillna(0)
    df["true_isomer_pairs"]       = df["true_isomer_pairs"].fillna(0).astype(int)

    log.info(f"  Targets: {len(df):,}")
    log.info(f"  Unique compounds (total): {df['unique_compounds'].sum():,}")
    log.info(f"  Stereochemical families (total): {df['stereochemical_families'].sum():,}")
    log.info(f"  True isomer pairs (total): {df['true_isomer_pairs'].sum():,}")
    log.info(f"  Literature references (total): {df['literature_references'].sum():,.0f}")
    return df


