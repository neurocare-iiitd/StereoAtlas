def minmax_norm(series: pd.Series) -> pd.Series:
    """Min-Max normalization → [0, 1]. Returns 0 when all values are equal."""
    mn, mx = series.min(), series.max()
    if mx == mn:
        return pd.Series(0.0, index=series.index)
    return (series - mn) / (mx - mn)


