# STEP 2 — Min-Max normalization
# ═══════════════════════════════════════════════════════════════════════════════

# Metrics included in DCS and their weights (equal weighting per spec)
# NOTE: 'organisms' is excluded — in TRUE_ISOMER_PAIRS every target maps to
# exactly 1 organism (zero variance), so it cannot be meaningfully normalized.
# Replaced with 'unique_pubmed_ids' which captures independent literature depth.
DCS_METRICS = [
    "stereochemical_families",
    "true_isomer_pairs",
    "activity_types",
    "unique_pubmed_ids",
    "literature_references",
    "median_fold_difference",
]

def step2_normalize(df: pd.DataFrame) -> pd.DataFrame:
    log.info("=" * 60)
    log.info("STEP 2 — Min-Max normalization")
    log.info("=" * 60)

    for metric in DCS_METRICS:
        normed_col = f"norm_{metric}"
        df[normed_col] = minmax_norm(df[metric])
        log.info(f"  norm_{metric:<35s}: min={df[normed_col].min():.3f}  max={df[normed_col].max():.3f}")

    return df


